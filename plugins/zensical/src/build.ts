import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { platformNav, type NavItem } from './nav.ts';

/** Zensical version and the date its unpinned Python dependencies are resolved at (`uvx --exclude-newer`). */
const zensical = { version: '0.0.74', resolvedAt: '2026-10-31T00:00:00Z' };

const platforms = [
  ['typescript', 'TypeScript'],
  ['kotlin', 'Kotlin'],
  ['swift', 'Swift'],
] as const;

// marks <out> as ours, so a rebuild may replace it
const marker = '# Generated by @rn-cross-platform-docs/zensical; replaced on each build.';

export interface BuildOptions {
  reference: string;
  out: string;
  siteUrl?: string;
}

/** Writes the Zensical project for the library at `root` to `options.out` and builds it. */
export async function build(root: string, options: BuildOptions): Promise<void> {
  const out = await writeProject(root, options);
  const args = ['--exclude-newer', zensical.resolvedAt, `zensical@${zensical.version}`, 'build'];
  const r = spawnSync('uvx', args, { cwd: out, stdio: 'inherit' });
  if ((r.error as NodeJS.ErrnoException | undefined)?.code === 'ENOENT') {
    throw new Error('`uvx` not found: uv is not on PATH; see https://docs.astral.sh/uv/getting-started/installation/');
  }
  if (r.error) throw r.error;
  if (r.status !== 0) {
    throw new Error(`\`${['uvx', ...args].join(' ')}\` in ${out} failed with ${r.signal ?? `exit code ${r.status}`}`);
  }
}

/**
 * Writes `zensical.toml` and `docs/` (README.md, guides/, one tree per platform, `.nav.yml` files) to `options.out`.
 * Refuses to replace an existing non-empty directory it didn't write. Returns the project's absolute path.
 */
export async function writeProject(root: string, { reference, out, siteUrl }: BuildOptions): Promise<string> {
  const ref = resolve(root, reference);
  const dir = resolve(root, out);
  const present = platforms.filter(([p]) => existsSync(join(ref, p)));
  if (!present.length) {
    throw new Error(`no typescript/, kotlin/ or swift/ in ${ref}; run \`rn-cross-platform-docs generate\` first`);
  }
  if (!existsSync(join(root, 'README.md'))) throw new Error(`no README.md in ${root}; it is the site's home page`);
  const toml = join(dir, 'zensical.toml');
  const ours = existsSync(toml) && (await readFile(toml, 'utf8')).startsWith(marker);
  if (!ours && existsSync(dir) && (await readdir(dir)).length) {
    throw new Error(`${dir} exists and wasn't written by this tool; pick another --out`);
  }
  if (!relative(dir, ref).startsWith('..')) throw new Error(`--reference must be outside --out`);

  const docs = join(dir, 'docs');
  await rm(docs, { recursive: true, force: true });
  await mkdir(docs, { recursive: true });
  const nav: NavItem[] = [];
  // README.md keeps its name, so links to it from guides (../README.md) still resolve; Zensical serves it as the index
  await cp(join(root, 'README.md'), join(docs, 'README.md'));
  nav.push({ Home: 'README.md' });
  if (existsSync(join(root, 'guides'))) {
    await cp(join(root, 'guides'), join(docs, 'guides'), { recursive: true });
    nav.push({ Guides: 'guides' });
  }
  for (const [p, title] of present) {
    await cp(join(ref, p), join(docs, p), { recursive: true });
    nav.push({ [title]: p });
    // TypeScript keeps TypeDoc's folders and only hides `_media/`
    const platformFile = p === 'typescript' ? { ignore: '_*' } : await platformNav(join(docs, p));
    await writeFile(join(docs, p, '.nav.yml'), JSON.stringify(platformFile));
  }
  await writeFile(join(docs, '.nav.yml'), JSON.stringify({ nav }));

  const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')) as Package;
  await writeFile(toml, config(pkg, siteUrl));
  return dir;
}

interface Package {
  name: string;
  description?: string;
  repository?: string | { url?: string };
}

const shorthandHosts: Record<string, string> = { github: 'github.com', gitlab: 'gitlab.com', bitbucket: 'bitbucket.org' };

/** The web URL of a package.json `repository`, or undefined for a form it doesn't recognize. */
export function repoUrl(repository: Package['repository']): string | undefined {
  const r = typeof repository === 'string' ? repository : repository?.url;
  if (!r) return undefined;
  const url = /^(?:git\+)?(?:https?|ssh|git):\/\/(?:[^@/]+@)?([^/:]+)(?::\d+)?[/:](.+?)(?:\.git)?\/?$/.exec(r);
  if (url) return `https://${url[1]}/${url[2]}`;
  const short = /^(?:(github|gitlab|bitbucket):)?([\w.-]+\/[\w.-]+)$/.exec(r);
  return short ? `https://${shorthandHosts[short[1] ?? 'github']}/${short[2]}` : undefined;
}

function config({ name, description, repository }: Package, siteUrl?: string): string {
  const repo = repoUrl(repository);
  const project = [
    `site_name = ${JSON.stringify(name)}`,
    description && `site_description = ${JSON.stringify(description)}`,
    siteUrl && `site_url = ${JSON.stringify(siteUrl)}`,
    // also sets edit_uri, which stays unused: no content.action.edit, as the pages aren't the repo's files
    repo && `repo_url = ${JSON.stringify(repo)}`,
  ].filter(Boolean);
  const features = [
    'content.code.copy',
    'content.tabs.link',
    'navigation.indexes',
    // a no-op without site_url: instant loading only takes links listed in sitemap.xml, which is empty then
    'navigation.instant',
    'navigation.instant.prefetch',
    'navigation.path',
    'navigation.tabs',
    'navigation.top',
    'navigation.tracking',
    'search.highlight',
    'toc.follow',
  ];
  return `${marker}
[project]
${project.join('\n')}

[project.theme]
features = ${JSON.stringify(features)}

# follows the OS setting until the reader picks light or dark
[[project.theme.palette]]
media = "(prefers-color-scheme)"
toggle.icon = "lucide/sun-moon"
toggle.name = "Switch to light mode"

[[project.theme.palette]]
media = "(prefers-color-scheme: light)"
scheme = "default"
toggle.icon = "lucide/sun"
toggle.name = "Switch to dark mode"

[[project.theme.palette]]
media = "(prefers-color-scheme: dark)"
scheme = "slate"
toggle.icon = "lucide/moon"
toggle.name = "Switch to system preference"

# Zensical's built-in awesome-nav replacement; reads docs/**/.nav.yml
[project.plugins.awesome-nav]

# Zensical's default extension set (setting this table replaces it), minus emoji, plus escapeall
[project.markdown_extensions]
abbr = {}
admonition = {}
attr_list = {}
def_list = {}
footnotes = {}
md_in_html = {}
toc.permalink = true
pymdownx.arithmatex.generic = true
pymdownx.betterem = {}
pymdownx.caret = {}
pymdownx.details = {}
# no pymdownx.emoji: it reads Swift argument labels as shortcodes, e.g. decode(_:in:) gets an 🇮🇳 flag
pymdownx.highlight.anchor_linenums = true
pymdownx.highlight.line_spans = "__span"
pymdownx.highlight.pygments_lang_class = true
pymdownx.inlinehilite = {}
pymdownx.keys = {}
pymdownx.magiclink = {}
pymdownx.mark = {}
pymdownx.smartsymbols = {}
pymdownx.superfences.custom_fences = [
  { name = "mermaid", class = "mermaid", format = "pymdownx.superfences.fence_code_format" },
]
pymdownx.tabbed.alternate_style = true
pymdownx.tabbed.combine_header_slug = true
pymdownx.tasklist.custom_checkbox = true
pymdownx.tilde = {}
# CommonMark escapes: TypeDoc's \\< and Dokka's trailing-backslash line breaks
pymdownx.escapeall.hardbreak = true
`;
}
