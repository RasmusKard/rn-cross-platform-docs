import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { cp, glob, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { platformNav, typescriptNav, type NavItem, type TypeDocNavItem } from './nav.ts';

/** Zensical version and the date its unpinned Python dependencies are resolved at (`uvx --exclude-newer`). */
const zensical = { version: '0.0.74', resolvedAt: '2026-10-31T00:00:00Z' };

const platforms = [
  ['typescript', 'TypeScript'],
  ['kotlin', 'Kotlin'],
  ['swift', 'Swift'],
] as const;

// marks <out> as ours, so a rebuild may replace it
const marker = '# Generated by @rn-cross-platform-docs/zensical; replaced on each build.';

export interface BuildOptions {
  reference: string;
  out: string;
  siteUrl?: string;
}

/** Writes the Zensical project for the library at `root` to `options.out` and builds it. */
export async function build(root: string, options: BuildOptions): Promise<void> {
  const out = await writeProject(root, options);
  const args = ['--exclude-newer', zensical.resolvedAt, `zensical@${zensical.version}`, 'build'];
  const result = spawnSync('uvx', args, { cwd: out, stdio: 'inherit' });
  if ((result.error as NodeJS.ErrnoException | undefined)?.code === 'ENOENT') {
    throw new Error('`uvx` not found: uv is not on PATH; see https://docs.astral.sh/uv/getting-started/installation/');
  }
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `\`${['uvx', ...args].join(' ')}\` in ${out} failed with ${result.signal ?? `exit code ${result.status}`}`,
    );
  }
}

/**
 * Writes `zensical.toml` and `docs/` (README.md, guides/, one tree per platform, `.nav.yml` files) to `options.out`.
 * Reference pages lose whatever precedes their H1 (breadcrumbs, page headers, metadata comments), Kotlin package
 * pages are titled by package name, and unlabeled code blocks in Swift pages are labeled `swift`.
 * Refuses to replace an existing non-empty directory it didn't write. Returns the project's absolute path.
 */
export async function writeProject(root: string, { reference, out, siteUrl }: BuildOptions): Promise<string> {
  const referenceDir = resolve(root, reference);
  const projectDir = resolve(root, out);
  const presentPlatforms = platforms.filter(([p]) => existsSync(join(referenceDir, p)));
  if (!presentPlatforms.length) {
    throw new Error(
      `no typescript/, kotlin/ or swift/ in ${referenceDir}; run \`rn-cross-platform-docs generate\` first`,
    );
  }
  if (!existsSync(join(root, 'README.md'))) throw new Error(`no README.md in ${root}; it is the site's home page`);
  const toml = join(projectDir, 'zensical.toml');
  const writtenByUs = existsSync(toml) && (await readFile(toml, 'utf8')).startsWith(marker);
  if (!writtenByUs && existsSync(projectDir) && (await readdir(projectDir)).length) {
    throw new Error(`${projectDir} exists and wasn't written by this tool; pick another --out`);
  }
  if (!relative(projectDir, referenceDir).startsWith('..')) throw new Error(`--reference must be outside --out`);

  const docs = join(projectDir, 'docs');
  await rm(docs, { recursive: true, force: true });
  await mkdir(docs, { recursive: true });
  const nav: NavItem[] = [];
  // README.md keeps its name, so links to it from guides (../README.md) still resolve; Zensical serves it as the index
  await cp(join(root, 'README.md'), join(docs, 'README.md'));
  nav.push({ Home: 'README.md' });
  if (existsSync(join(root, 'guides'))) {
    await cp(join(root, 'guides'), join(docs, 'guides'), { recursive: true });
    nav.push({ Guides: 'guides' });
    const guidesNavFile = join(docs, 'guides/.nav.yml');
    if (!existsSync(guidesNavFile)) await writeFile(guidesNavFile, JSON.stringify(await guidesNav(root, docs)));
  }
  for (const [p, title] of presentPlatforms) {
    await cp(join(referenceDir, p), join(docs, p), { recursive: true });
    await tidyPages(join(docs, p), p === 'swift');
    nav.push({ [title]: p });
    await writeFile(join(docs, p, '.nav.yml'), JSON.stringify(await treeNav(join(docs, p), p)));
  }
  await writeFile(join(docs, '.nav.yml'), JSON.stringify({ nav }));
  // the theme sets h5 in capitals, which TypeDoc uses for parameter names
  await writeFile(join(docs, 'extra.css'), '.md-typeset h5 { text-transform: none; }\n');

  const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')) as Package;
  await writeFile(toml, zensicalToml(pkg, siteUrl));
  return projectDir;
}

/** The `.nav.yml` contents for the platform tree at `dir`. Removes the files in it that the site shouldn't publish. */
async function treeNav(dir: string, platform: string): Promise<object> {
  if (platform !== 'typescript') {
    const nav = await platformNav(dir);
    // Dokka's root page, when the nav shows its one package in its place: search and the sitemap would still list it
    if (platform === 'kotlin' && !nav.nav.includes('index.md')) await rm(join(dir, 'index.md'), { force: true });
    return nav;
  }
  const navigationJson = join(dir, 'navigation.json');
  // a tree made without the navigation JSON: TypeDoc's folders, minus `_media/` and `documents/` (the guides)
  if (!existsSync(navigationJson)) return { ignore: ['_*', 'documents'] };
  const json = JSON.parse(await readFile(navigationJson, 'utf8')) as TypeDocNavItem[];
  await rm(navigationJson);
  return await typescriptNav(dir, json);
}

// TypeDoc's page header and breadcrumbs, Dokka's `//[lib]/[package]/...` breadcrumb and DocC's metadata comment come
// before the H1: they repeat the site's breadcrumbs, and Zensical's search gives the text before an H1 its own entry,
// listing each page twice. Dokka titles every package page "Package-level declarations"; its folder is named after the
// package. DocC writes declarations in unlabeled code blocks, which get labeled `swift` for syntax highlighting.
async function tidyPages(dir: string, swift: boolean): Promise<void> {
  for await (const page of glob('**/*.md', { cwd: dir })) {
    const md = await readFile(join(dir, page), 'utf8');
    const pkg = basename(dirname(page));
    let tidy = dropBeforeH1(md).replace(/^# Package-level declarations$/m, (h) => (pkg === '.' ? h : `# ${pkg}`));
    if (swift)
      tidy = tidy.replace(codeBlock, (block, lang: string, rest: string) => (lang ? block : `\`\`\`swift\n${rest}`));
    await writeFile(join(dir, page), tidy);
  }
}

const codeBlock = /^```(.*)\n([\s\S]*?^```)$/gm;

// keeps front matter; a page whose first `# ` line follows a code fence (no H1) stays whole
function dropBeforeH1(md: string): string {
  const front = /^---\n[\s\S]*?\n---\n/.exec(md)?.[0] ?? '';
  const rest = md.slice(front.length);
  const first = /^(?:# |```|~~~)/m.exec(rest);
  return first?.[0] === '# ' ? front + rest.slice(first.index) : md;
}

/** The guides in the order the README links them, then the rest, if there are any. */
async function guidesNav(root: string, docs: string): Promise<{ nav: string[] }> {
  const readme = await readFile(join(root, 'README.md'), 'utf8');
  const linked = [...readme.matchAll(/\]\((?:\.\/)?guides\/([^)#\s]+\.md)/g)].map((m) => m[1]);
  const nav = [...new Set(linked)].filter((f) => existsSync(join(docs, 'guides', f)));
  // awesome-nav warns about a `*` that matches nothing
  for await (const f of glob('**/*.md', { cwd: join(docs, 'guides') })) {
    if (!nav.includes(f)) return { nav: [...nav, '*'] };
  }
  return { nav };
}

interface Package {
  name: string;
  description?: string;
  repository?: string | { url?: string };
}

const shorthandHosts: Record<string, string> = {
  github: 'github.com',
  gitlab: 'gitlab.com',
  bitbucket: 'bitbucket.org',
};

/** The web URL of a package.json `repository`, or undefined for a form it doesn't recognize. */
export function repoUrl(repository: Package['repository']): string | undefined {
  const spec = typeof repository === 'string' ? repository : repository?.url;
  if (!spec) return undefined;
  const url = /^(?:git\+)?(?:https?|ssh|git):\/\/(?:[^@/]+@)?([^/:]+)(?::\d+)?[/:](.+?)(?:\.git)?\/?$/.exec(spec);
  if (url) return `https://${url[1]}/${url[2]}`;
  const short = /^(?:(github|gitlab|bitbucket):)?([\w.-]+\/[\w.-]+)$/.exec(spec);
  return short ? `https://${shorthandHosts[short[1] ?? 'github']}/${short[2]}` : undefined;
}

function zensicalToml({ name, description, repository }: Package, siteUrl?: string): string {
  const repo = repoUrl(repository);
  const project = [
    `site_name = ${JSON.stringify(name)}`,
    description && `site_description = ${JSON.stringify(description)}`,
    siteUrl && `site_url = ${JSON.stringify(siteUrl)}`,
    // also sets edit_uri, which stays unused: no content.action.edit, as the pages aren't the repo's files
    repo && `repo_url = ${JSON.stringify(repo)}`,
    'extra_css = ["extra.css"]',
    // TypeDoc's copies of files that documents link to, such as the README, whose own links don't resolve there
    'exclude_docs = """\ntypescript/_media/*.md\n"""',
  ].filter(Boolean);
  const features = [
    'content.code.copy',
    'content.tabs.link',
    'navigation.indexes',
    // a no-op without site_url: instant loading only takes links listed in sitemap.xml, which is empty then
    'navigation.instant',
    'navigation.instant.prefetch',
    'navigation.path',
    'navigation.tabs',
    'navigation.top',
    'navigation.tracking',
    'search.highlight',
    'toc.follow',
  ];
  return `${marker}
[project]
${project.join('\n')}

[project.theme]
features = ${JSON.stringify(features)}

# follows the OS setting until the reader picks light or dark
[[project.theme.palette]]
media = "(prefers-color-scheme)"
toggle.icon = "lucide/sun-moon"
toggle.name = "Switch to light mode"

[[project.theme.palette]]
media = "(prefers-color-scheme: light)"
scheme = "default"
toggle.icon = "lucide/sun"
toggle.name = "Switch to dark mode"

[[project.theme.palette]]
media = "(prefers-color-scheme: dark)"
scheme = "slate"
toggle.icon = "lucide/moon"
toggle.name = "Switch to system preference"

# Zensical's built-in awesome-nav replacement; reads docs/**/.nav.yml
[project.plugins.awesome-nav]

# Zensical's default extension set (setting this table replaces it), minus emoji, plus escapeall
[project.markdown_extensions]
abbr = {}
admonition = {}
attr_list = {}
def_list = {}
footnotes = {}
md_in_html = {}
toc.permalink = true
# member headings only; TypeDoc's Parameters/Returns headings under each member would crowd the page TOC
toc.toc_depth = 3
pymdownx.arithmatex.generic = true
pymdownx.betterem = {}
pymdownx.caret = {}
pymdownx.details = {}
# no pymdownx.emoji: it reads Swift argument labels as shortcodes, e.g. decode(_:in:) gets an 🇮🇳 flag
pymdownx.highlight.anchor_linenums = true
pymdownx.highlight.line_spans = "__span"
pymdownx.highlight.pygments_lang_class = true
pymdownx.inlinehilite = {}
pymdownx.keys = {}
pymdownx.magiclink = {}
pymdownx.mark = {}
pymdownx.smartsymbols = {}
pymdownx.superfences.custom_fences = [
  { name = "mermaid", class = "mermaid", format = "pymdownx.superfences.fence_code_format" },
]
pymdownx.tabbed.alternate_style = true
pymdownx.tabbed.combine_header_slug = true
pymdownx.tasklist.custom_checkbox = true
pymdownx.tilde = {}
# CommonMark escapes: TypeDoc's \\< and Dokka's trailing-backslash line breaks
pymdownx.escapeall.hardbreak = true
`;
}
